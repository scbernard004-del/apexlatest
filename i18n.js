const escapeRegex=s=>s.replace(/[.*+?^${}()|[\]\\]/g,'\\$&');
const patterns=Object.entries(sw).filter(([key])=>key.includes('{')).map(([key,value])=>{
 const names=[...key.matchAll(/\{(\w+)\}/g)].map(m=>m[1]);
 const regex=new RegExp('^'+key.split(/\{\w+\}/g).map(escapeRegex).join('(.+?)')+'$');
 return {regex,names,value};
});
